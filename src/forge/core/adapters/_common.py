"""Types and helpers shared by the adapter modules (ADR 0014)."""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from forge.core.config import ADAPTERS, ForgeConfig
from forge.core.models import resolve
from forge.core.presets import Preset
from forge.core.profile import AgentProfile
from forge.core.prompts import (
    AgentDef,
    Prompt,
    load_agents,
    load_prompts,
    load_rules,
    parse_agents,
    parse_prompts,
)
from forge.core.tiers import TASK_TIER

GENERATED_MARK = "generated by `forge adapters generate"
"""Text every generated file carries in its header; used to recognise generated files."""

SKILL_PREFIX = "forge-"


@dataclass(frozen=True)
class GeneratedFile:
    """A file an adapter renders. ``path`` is repository-relative.

    With ``region=True`` the file is human-owned and ``content`` is only the inner text of
    its Forge-managed region (``AGENTS.md``, ``CLAUDE.md``).
    """

    path: Path
    content: str
    region: bool = False


@dataclass(frozen=True)
class Project:
    """Everything the project-level adapters render from."""

    name: str
    default_branch: str
    merge_method: str
    adapters: tuple[str, ...]
    rules: str
    prompts: tuple[Prompt, ...]
    agents: tuple[AgentDef, ...]


def load_project(repo_root: Path, config: ForgeConfig) -> Project:
    """Read `.forge/rules.md`, prompts and subagent definitions under ``repo_root``."""
    return Project(
        name=config.project.name,
        default_branch=config.project.default_branch,
        merge_method=config.project.merge_method,
        adapters=config.adapters,
        rules=load_rules(repo_root),
        prompts=load_prompts(repo_root),
        agents=load_agents(repo_root),
    )


def project_from_texts(
    *,
    name: str,
    default_branch: str,
    merge_method: str = "squash",
    adapters: tuple[str, ...] = ADAPTERS,
    rules: str,
    prompts: Mapping[Path, str],
    agents: Mapping[Path, str],
) -> Project:
    """Build a :class:`Project` from in-memory file texts (used by ``forge init``)."""
    return Project(
        name=name,
        default_branch=default_branch,
        merge_method=merge_method,
        adapters=adapters,
        rules=rules,
        prompts=parse_prompts(prompts),
        agents=parse_agents(agents),
    )


def md_header(source: str, *, local: bool = False) -> str:
    """Markdown header of a generated file: generated from ``source``, do not edit."""
    flag = " --local" if local else ""
    return f"<!-- {GENERATED_MARK}{flag}` from {source}; do not edit -->"


def hash_header(source: str, *, local: bool = False) -> str:
    """YAML/TOML comment header of a generated file."""
    flag = " --local" if local else ""
    return f"# {GENERATED_MARK}{flag}` from {source}; do not edit"


def frontmatter(data: Mapping[str, Any]) -> str:
    """Render a YAML frontmatter block (``---`` lines included), keys in the given order."""
    dumped = yaml.safe_dump(
        dict(data), sort_keys=False, allow_unicode=True, default_flow_style=False, width=10**6
    )
    return f"---\n{dumped}---\n"


def is_generated(text: str) -> bool:
    """True if ``text`` carries the generated-file header in its first lines."""
    head = "\n".join(text.splitlines()[:20])
    return GENERATED_MARK in head


def normalize_body(body: str) -> str:
    """Return a prompt/agent body with ``\\n`` line endings, trimmed of surrounding blank lines."""
    return body.replace("\r\n", "\n").strip("\n")


@dataclass(frozen=True)
class SubagentModel:
    """Concrete model and effort for one rendered subagent.

    ``model`` is ``None`` when the subagent must inherit the main session's model (tier
    ``task``, or a tier the agent cannot serve). ``effort`` is the tool-specific value, or
    ``None`` when it must be left out.
    """

    model: str | None
    effort: str | None
    warnings: tuple[str, ...] = ()


def resolve_subagent(
    definition: AgentDef,
    agent: AgentProfile,
    config: ForgeConfig,
    presets: Mapping[str, Preset] | None,
    *,
    allowed_efforts: tuple[str, ...],
    tool_label: str,
) -> SubagentModel:
    """Resolve ``definition``'s tier/effort for ``agent`` (ADR 0005, ADR 0014).

    The subagent's name is passed as its role, so ``models.min_tier_for`` can raise it.
    ``allowed_efforts`` are the effort values the target tool accepts; others are dropped
    with a warning.
    """
    res = resolve(
        agent,
        declared_tier=definition.tier,
        declared_effort=definition.effort,
        roles=[definition.name],
        constraints=config.models,
        presets=presets,
    )
    where = f"subagent {definition.name} ({tool_label}, agent {agent.id})"
    warnings: list[str] = []
    model: str | None
    if definition.tier == TASK_TIER:
        model = None
    elif not res.served or res.model is None:
        model = None
        warnings.append(
            f"{where}: agent cannot serve tier {res.tier}; rendered without a model so it "
            "inherits the main session's model"
        )
    else:
        model = res.model
    effort = res.effort_value
    preset = presets.get(agent.tool) if presets is not None else None
    supports = preset is None or preset.supports_effort
    if effort is not None and effort not in allowed_efforts:
        warnings.append(
            f"{where}: effort value {effort!r} is not one of {', '.join(allowed_efforts)}; "
            "effort left out"
        )
        effort = None
    elif effort is None and supports:
        warnings.append(f"{where}: no effort mapping for {res.effort}; effort left out")
    return SubagentModel(model=model, effort=effort, warnings=tuple(warnings))


