"""`forge docs`: the generated command reference (ADR 0015).

The reference is rendered from a neutral description of the CLI (:class:`CliDoc`, built from
the Click command tree by ``forge.commands.docs``) and from the prompt frontmatter. It never
uses rendered ``--help`` output, so it is identical regardless of terminal width, colours
or environment.

- Commands and subcommands are listed in alphabetical order of their full path.
- Parameters keep their declaration order (arguments first, then options).

``core/`` cannot import the CLI, so the command layer registers a provider with
:func:`register_cli`; :func:`registered_cli` is what ``forge init`` uses to write
`docs/forge/commands.md`.
"""

from __future__ import annotations

import difflib
import re
from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

from forge.core.errors import ForgeError, PreconditionError
from forge.core.prompts import PROMPTS_DIR, Prompt, parse_prompts, read_text

DEFAULT_OUTPUT = Path("docs/forge/commands.md")
"""Default ``--output`` of `forge docs`, relative to the repository root."""

DEFAULT_PROMPTS = PROMPTS_DIR
"""Default ``--prompts`` of `forge docs`, relative to the repository root."""

GENERATED_MARKER = "<!-- generated by `forge docs`; do not edit. -->"

DIFF_LINES = 12
"""How many differing lines ``--check`` reports at most."""

_ANSI_RE = re.compile(r"\x1b\[[0-9;?]*[ -/]*[@-~]")
_SPACE_RE = re.compile(r"\s+")


@dataclass(frozen=True)
class ParamDoc:
    """One argument or option of a command, with every value already rendered as text."""

    kind: Literal["argument", "option"]
    names: tuple[str, ...]
    type: str
    required: bool = False
    default: str | None = None
    choices: tuple[str, ...] = ()
    help: str = ""
    envvar: str | None = None


@dataclass(frozen=True)
class CommandDoc:
    """One command or group. ``path`` starts with the program name (``("forge", "task")``)."""

    path: tuple[str, ...]
    usage: str
    help: str = ""
    params: tuple[ParamDoc, ...] = ()
    subcommands: tuple[CommandDoc, ...] = ()


@dataclass(frozen=True)
class CliDoc:
    """The whole CLI: the root group, and the global options also accepted after a command."""

    root: CommandDoc
    after_subcommand: tuple[str, ...] = field(default_factory=tuple)


# -- provider registry ------------------------------------------------------------------------

_provider: Callable[[], CliDoc] | None = None


def register_cli(provider: Callable[[], CliDoc]) -> None:
    """Register the function that describes the CLI (called by ``forge.commands.docs``)."""
    global _provider
    _provider = provider


def registered_cli() -> CliDoc:
    """Describe the CLI with the registered provider.

    Raises :class:`ForgeError` when no provider is registered (the CLI was not loaded).
    """
    if _provider is None:
        raise ForgeError(
            "the command reference is unavailable: the CLI is not loaded",
            hint="import forge.commands.docs (or forge.cli) before rendering the reference",
        )
    return _provider()


# -- text helpers -----------------------------------------------------------------------------


def clean_text(text: str | None) -> str:
    """Strip ANSI escapes, Click's ``\\f`` truncation and surrounding blank space."""
    if not text:
        return ""
    text = _ANSI_RE.sub("", text).split("\f", 1)[0]
    lines = [line.rstrip() for line in text.strip().splitlines()]
    return "\n".join(lines)


def _cell(text: str) -> str:
    """One Markdown table cell: single line, pipes escaped, never empty."""
    flat = _SPACE_RE.sub(" ", clean_text(text)).strip().replace("|", "\\|")
    return flat or "-"


def _code(text: str) -> str:
    return f"`{text}`" if text else ""


def walk(command: CommandDoc) -> Iterable[CommandDoc]:
    """Every command below ``command`` (not itself), in alphabetical order of path."""
    for sub in sorted(command.subcommands, key=lambda c: c.path):
        yield sub
        yield from walk(sub)


def _anchor(path: Sequence[str]) -> str:
    return "-".join(path)


# -- rendering --------------------------------------------------------------------------------


def _param_table(params: Sequence[ParamDoc], kind: Literal["argument", "option"]) -> list[str]:
    rows = [p for p in params if p.kind == kind]
    if not rows:
        return []
    title = "Argument" if kind == "argument" else "Option"
    out = [
        f"| {title} | Type | Required | Default | Description |",
        "| --- | --- | --- | --- | --- |",
    ]
    for p in rows:
        names = ", ".join(_code(n) for n in p.names)
        desc = clean_text(p.help)
        extras: list[str] = []
        if p.choices:
            extras.append("Choices: " + ", ".join(_code(c) for c in p.choices) + ".")
        if p.envvar:
            extras.append(f"Env: {_code(p.envvar)}.")
        if extras:
            desc = " ".join([desc, *extras]) if desc else " ".join(extras)
        default = _code(p.default) if p.default not in (None, "") else ""
        out.append(
            f"| {_cell(names)} | {_cell(p.type)} | {'yes' if p.required else 'no'} "
            f"| {_cell(default)} | {_cell(desc)} |"
        )
    return out


def _command_section(command: CommandDoc) -> list[str]:
    out = [f"### `{' '.join(command.path)}`", "", "```text", command.usage, "```", ""]
    help_text = clean_text(command.help)
    if help_text:
        out += [help_text, ""]
    for table in (
        _param_table(command.params, "argument"),
        _param_table(command.params, "option"),
    ):
        if table:
            out += [*table, ""]
    if command.subcommands:
        out.append("Subcommands:")
        out.append("")
        for sub in sorted(command.subcommands, key=lambda c: c.path):
            out.append(f"- [`{' '.join(sub.path)}`](#{_anchor(sub.path)})")
        out.append("")
    return out


def _prompt_table(prompts: Sequence[Prompt]) -> list[str]:
    if not prompts:
        return ["No prompts found.", ""]
    out = ["| Prompt | Description | Args | Roles |", "| --- | --- | --- | --- |"]
    for p in prompts:
        roles = ", ".join(p.roles)
        out.append(
            f"| {_cell(_code(p.name))} | {_cell(p.description)} "
            f"| {_cell(_code(p.args))} | {_cell(roles)} |"
        )
    return [*out, ""]


def render_reference(cli: CliDoc, prompts: Sequence[Prompt]) -> str:
    """Render the Markdown command reference. Deterministic for the same inputs."""
    root = cli.root
    prog = root.path[0] if root.path else "forge"
    out = [
        f"# `{prog}` command reference",
        "",
        GENERATED_MARKER,
        "",
        f"Generated by `{prog} docs` from the command tree and the prompt frontmatter; "
        f"do not edit. Run `{prog} docs` to regenerate it and `{prog} docs --check` to verify it.",
        "",
        "```text",
        root.usage,
        "```",
        "",
    ]
    help_text = clean_text(root.help)
    if help_text:
        out += [help_text, ""]
    out += ["## Global options", ""]
    if cli.after_subcommand:
        listed = ", ".join(_code(n) for n in cli.after_subcommand)
        out += [
            f"Global options go before the command (`{prog} --json status`). "
            f"{listed} are also accepted after it (`{prog} status --json`).",
            "",
        ]
    out += [*_param_table(root.params, "option"), ""]
    out += [
        "Every command also accepts `--help`. Exit codes: 0 ok, 1 error, 2 agent action, "
        "3 nothing available, 4 escalation, 5 precondition (spec §16).",
        "",
        "## Commands",
        "",
    ]
    for command in walk(root):
        out += [f'<a id="{_anchor(command.path)}"></a>', ""]
        out += _command_section(command)
    out += ["## Prompts", ""]
    out += _prompt_table(prompts)
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


# -- prompts, check, write --------------------------------------------------------------------


def load_prompts_dir(repo_root: Path, prompts_dir: Path) -> tuple[Prompt, ...]:
    """Load and validate every ``*.md`` prompt in ``prompts_dir`` (relative to ``repo_root``).

    Raises :class:`PreconditionError` (exit 5) when the directory is missing, and
    :class:`ConfigError` when a prompt is invalid.
    """
    directory = prompts_dir if prompts_dir.is_absolute() else repo_root / prompts_dir
    if not directory.is_dir():
        raise PreconditionError(
            f"prompts directory not found: {directory}",
            hint="run `forge init` to create .forge/prompts, or pass --prompts <dir>",
        )
    texts: dict[Path, str] = {}
    for path in sorted(directory.glob("*.md")):
        if path.is_file():
            try:
                rel = path.relative_to(repo_root)
            except ValueError:
                rel = path
            texts[rel] = read_text(path)
    return parse_prompts(texts)


def diff_summary(path: Path, current: str | None, expected: str) -> list[str]:
    """Why ``current`` (the file's text, ``None`` if missing) differs from ``expected``.

    Empty when they are equal; otherwise at most :data:`DIFF_LINES` lines.
    """
    if current == expected:
        return []
    if current is None:
        return [f"{path.as_posix()} is missing"]
    diff = difflib.unified_diff(
        current.splitlines(),
        expected.splitlines(),
        fromfile=f"{path.as_posix()} (current)",
        tofile=f"{path.as_posix()} (expected)",
        n=0,
        lineterm="",
    )
    lines = [line for line in diff if not line.startswith(("---", "+++"))]
    if not lines:  # only trailing newline / line-ending differences
        return [f"{path.as_posix()} differs in whitespace or line endings"]
    if len(lines) > DIFF_LINES:
        lines = [*lines[:DIFF_LINES], f"... ({len(lines) - DIFF_LINES} more diff lines)"]
    return lines


def check_reference(path: Path, expected: str, *, label: Path | None = None) -> list[str]:
    """Compare the file at ``path`` with ``expected``; the diff summary (empty if equal).

    ``label`` is the path shown in the summary (default: ``path``).
    """
    current = read_text(path) if path.is_file() else None
    return diff_summary(label if label is not None else path, current, expected)


def write_reference(path: Path, text: str) -> bool:
    """Write ``text`` to ``path`` (creating parents). Returns whether the file changed."""
    if path.is_file() and read_text(path) == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("utf-8"))
    return True


